// Regenerates docs/API_CONTRACTS_PENDING.md from src/endpoints.ts.
// Run from the repo root: node packages/contracts/scripts/generate-docs.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("packages/contracts/src/endpoints.ts", "utf8");
let mockSrc = "";
try {
  mockSrc = readFileSync("apps/web/src/lib/api/mock/transport.ts", "utf8");
} catch {}

const rows = [...src.matchAll(/"([\w.]+)": d\("(\w+)", "([^"]+)", "([\w-]+)", "([^"]+)"(?:, "(\w+)")?\)/g)].map((m) => ({
  key: m[1], method: m[2], path: m[3], owner: m[4], purpose: m[5], status: m[6] ?? "draft",
}));
const mocked = new Set([...mockSrc.matchAll(/^  "([\w.]+)": \(/gm)].map((m) => m[1]));
const by501 = new Set([...mockSrc.matchAll(/^  "([\w.]+)": \(\) =>\s*\n?\s*fail\(501/gm)].map((m) => m[1]));
const streams = new Set(["projects.events", "agent.tasks.events", "builds.logs.stream"]);

const OWNER_TITLE = {
  backend: "Backend (auth, users, projects, files, usage, billing, admin) — Person 4 per the role brief; confirm",
  "agent-orchestration": "AI agent orchestration — confirm owner",
  "build-workers": "Build and test workers — confirm owner",
  "code-generation": "Code-generation engine — confirm owner",
};

const out = [
  "# API contracts needed by the frontend",
  "",
  "Generated by `node packages/contracts/scripts/generate-docs.mjs` from `packages/contracts/src/endpoints.ts`, the registry the API client uses. Every row is **draft** until its owner confirms it; then set `status` in the registry to `agreed` or `live` and regenerate.",
  "",
  "Types for each group live in `packages/contracts/src/<group>.ts`. Conventions the frontend assumed, to confirm with backend:",
  "",
  "- All endpoints under `/api/v1`, JSON bodies, error envelope `{ error: { code, message, fields?, requestId? } }`.",
  "- Session auth via an httpOnly cookie; Next.js proxies `/api/v1/*` to `BACKEND_URL` so the cookie is first-party.",
  "- Lists that can grow return `{ items, nextCursor, total? }`.",
  "- Live updates use server-sent events with named events (`event: task.updated`) carrying JSON.",
  "- Terminal: `POST /projects/{id}/terminal/sessions` returns a short-lived `wss://` URL to an isolated per-project sandbox. The frontend only connects to that URL.",
  "- Uploads: create session → PUT to pre-signed URL → complete → poll status.",
  "- A 404 without the error envelope, or a 501, is shown as a *Waiting for backend* state.",
  "",
];
for (const owner of Object.keys(OWNER_TITLE)) {
  const list = rows.filter((r) => r.owner === owner);
  if (!list.length) continue;
  out.push(`## ${OWNER_TITLE[owner]}`, "", "| Key | Method | Path | Purpose | Contract | Dev mock |", "|---|---|---|---|---|---|");
  for (const r of list) {
    const mock = streams.has(r.key) ? "yes (in-memory bus)" : by501.has(r.key) ? "no (501 by design)" : mocked.has(r.key) ? "yes" : "no";
    out.push(`| \`${r.key}\` | ${r.method} | \`${r.path}\` | ${r.purpose} | ${r.status} | ${mock} |`);
  }
  out.push("");
}
writeFileSync("docs/API_CONTRACTS_PENDING.md", out.join("\n"));
console.log(`Wrote ${rows.length} endpoints to docs/API_CONTRACTS_PENDING.md`);
